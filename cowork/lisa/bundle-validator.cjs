const fs = require("node:fs");
const path = require("node:path");
const esbuild = require("esbuild");

// Keep the runtime and its license notices in one offline companion file.
const result = esbuild.buildSync({
  absWorkingDir: __dirname,
  entryPoints: ["validator.cjs"],
  bundle: true, platform: "node", target: "node20", minify: true,
  legalComments: "inline", metafile: true, write: false,
});
const packages = new Set(Object.keys(result.metafile.inputs)
  .filter(name => name.startsWith("node_modules/")).map(name => name.split("/")[1]));
const notices = [...packages].sort().map(name => {
  const root = path.join(__dirname, "node_modules", name);
  const license = fs.readdirSync(root).find(file => /^license(?:\.txt|\.md)?$/i.test(file));
  return `${name}\n${fs.readFileSync(path.join(root, license), "utf8").trim()}`;
}).join("\n\n").replace(/\r\n/g, "\n");
fs.writeFileSync(path.resolve(__dirname, "../skills/design-validator.cjs"),
  `/* Generated by npm run bundle in cowork/lisa.\n\n${notices}\n*/\n${result.outputFiles[0].text}`);
